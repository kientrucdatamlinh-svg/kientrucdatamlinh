        // Quick Lu Ban 38.8cm Checker function
        function checkLoBanDirect() {
            const val = parseFloat(document.getElementById('loBanInput').value);
            const res = document.getElementById('loBanResult');
            if (!val || val <= 0) {
                res.style.display = 'none';
                return;
            }

            const cycle = 38.8;
            const pos = val % cycle;
            // Lu Ban 38.8cm has 10 segments of 3.88cm each:
            // 0: Đinh (Tốt)
            // 1: Hại (Xấu)
            // 2: Vượng (Tốt)
            // 3: Khổ (Xấu)
            // 4: Nghĩa (Tốt)
            // 5: Quan (Tốt)
            // 6: Tử (Xấu)
            // 7: Hưng (Tốt)
            // 8: Thất (Xấu)
            // 9: Tài (Tốt)
            const seg = Math.floor(pos / 3.88);
            const goodSegs = {
                0: "Cung ĐINH (Tốt - Đỗ đạt, Phúc lộc, Đăng khoa)",
                2: "Cung VƯỢNG (Tốt - Hưng vượng, Tiến bảo, Thêm đinh)",
                4: "Cung NGHĨA (Tốt - Đại cát, Quý tử, Thiên khố)",
                5: "Cung QUAN (Tốt - Thuận hòa, Phú quý, Tiến bảo)",
                7: "Cung HƯNG (Tốt - Hưng vượng, Sinh quý tử)",
                9: "Cung TÀI (Tốt - Tài đức, Nghinh phúc, Đắc lộc)"
            };

            const badSegs = {
                1: "Cung HẠI (Xấu - Bệnh tật, Khẩu thiệt)",
                3: "Cung KHỔ (Xấu - Mất mát, Tai ương)",
                6: "Cung TỬ (Xấu - Ly biệt, Thoát tài)",
                8: "Cung THẤT (Xấu - Suy sụp, Thoát khí)"
            };

            res.style.display = 'block';
            if (goodSegs[seg]) {
                res.className = 'lo-ban-result lo-ban-good';
                res.innerHTML = `<i class="fa-solid fa-circle-check"></i> ${goodSegs[seg]}`;
            } else {
                res.className = 'lo-ban-result lo-ban-bad';
                res.innerHTML = `<i class="fa-solid fa-triangle-exclamation"></i> ${badSegs[seg] || 'Cung xấu'}`;
            }
        }

                function toggleMobileMenu() {
            const menu = document.getElementById('navMenu');
            const toggleIcon = document.querySelector('.menu-toggle i');
            if (menu) {
                const isActive = menu.classList.toggle('active');
                if (toggleIcon) {
                    if (isActive) {
                        toggleIcon.classList.remove('fa-bars');
                        toggleIcon.classList.add('fa-xmark');
                    } else {
                        toggleIcon.classList.remove('fa-xmark');
                        toggleIcon.classList.add('fa-bars');
                    }
                }
                document.body.style.overflow = isActive ? 'hidden' : '';
            }
        }
