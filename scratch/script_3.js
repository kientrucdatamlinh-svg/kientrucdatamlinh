        // Get 5 recommended products matching article content
        function getRecommendedProducts(article) {
            let prods = (typeof DEFAULT_PRODUCTS !== 'undefined') ? DEFAULT_PRODUCTS : [];
            try {
                const localTs = parseInt(localStorage.getItem('ktdtl_last_saved_ts') || '0');
                const defaultTs = (typeof DEFAULT_DATA_TIMESTAMP !== 'undefined') ? DEFAULT_DATA_TIMESTAMP : 0;
                if (localTs > defaultTs && localStorage.getItem('ktdtl_products')) {
                    prods = JSON.parse(localStorage.getItem('ktdtl_products'));
                }
            } catch(e){}

            if (!prods || prods.length === 0) return [];

            const title = (article.title || '').toLowerCase();
            const cat = (article.category || '').toLowerCase();

            let matched = [];
            if (cat === 'cam-nang' || title.includes('lăng mộ') || title.includes('gia tộc')) {
                matched = prods.filter(p => p.cat_code === 'langtho' || p.cat_code === 'khulangmo' || p.cat_code === 'cuonthu');
            } else if (cat === 'phong-thuy' || title.includes('lỗ ban') || title.includes('kích thước') || title.includes('hướng')) {
                matched = prods.filter(p => p.cat_name.includes('Mộ') || p.cat_code === 'moda' || p.cat_code === 'thapda');
            } else if (cat === 'chon-da' || title.includes('đá') || title.includes('xanh rêu') || title.includes('granite')) {
                matched = prods.filter(p => (p.material || '').toLowerCase().includes('xanh rêu') || (p.title || '').toLowerCase().includes('rêu') || (p.material || '').toLowerCase().includes('granite'));
            }

            // Ensure 10 unique products
            const result = [];
            const seen = new Set();
            for (let p of matched) {
                if (!seen.has(p.title)) {
                    seen.add(p.title);
                    result.push(p);
                    if (result.length >= 10) break;
                }
            }
            if (result.length < 10) {
                for (let p of prods) {
                    if (!seen.has(p.title)) {
                        seen.add(p.title);
                        result.push(p);
                        if (result.length >= 10) break;
                    }
                }
            }
            return result.slice(0, 10);
        }


